import os
import sys
import pytest
from fastapi.testclient import TestClient
from sqlalchemy import create_engine
from sqlalchemy.orm import sessionmaker
from sqlalchemy.pool import StaticPool

# Ensure backend directory is in python path
backend_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if backend_dir not in sys.path:
    sys.path.insert(0, backend_dir)

from app.core.database import Base, get_db
from app.main import app
from app.models.user import User
from app.services.privacy_service import PrivacyService

# In-memory SQLite for isolated, blazing-fast tests
TEST_DB_URL = "sqlite:///:memory:"

test_engine = create_engine(
    TEST_DB_URL,
    connect_args={"check_same_thread": False},
    poolclass=StaticPool
)
TestingSessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=test_engine)


@pytest.fixture(scope="function")
def db_session():
    """Create fresh database tables for each test function."""
    Base.metadata.create_all(bind=test_engine)
    session = TestingSessionLocal()
    
    # Seed default test user
    user = User(id=1, name="Test User", email="test@chronis.ai")
    session.add(user)
    session.commit()
    session.refresh(user)
    PrivacyService.ensure_default_permissions(session, user.id)

    try:
        yield session
    finally:
        session.close()
        Base.metadata.drop_all(bind=test_engine)


